import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin, type ResolvedConfig } from 'vite';
import { site } from '../../scripts/lib/site-node.mjs';
import { renderInstallAgents } from './src/landing/install-agents.ts';
import { renderSarah, type SarahSummary } from './src/landing/sarah.ts';

const here = path.dirname(fileURLToPath(import.meta.url));

/**
 * The app must not talk to anything. Beyond not having any network code, the browser is told so:
 * connect-src 'none' blocks fetch/XHR/WebSocket, and nothing may load from another origin.
 * (Injected for the production build only; the dev server needs inline scripts and a websocket.)
 */
const APP_CSP = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'none'",
  "manifest-src 'self'",
  "worker-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

function appCsp(): Plugin {
  return {
    name: 'loam-app-csp',
    apply: 'build',
    transformIndexHtml: {
      order: 'post',
      handler(_html, ctx) {
        if (!ctx.filename.replace(/\\/g, '/').endsWith('/app/index.html')) return undefined;
        return [{ tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: APP_CSP }, injectTo: 'head-prepend' }];
      },
    },
  };
}

/**
 * Offline support without a single fetch() in our code: the worker only precaches the built files
 * (cache.addAll) and answers requests for them from the cache. The new version waits until every
 * tab is closed, so a page never loses the chunks it was built with.
 */
function appServiceWorker(): Plugin {
  let config: ResolvedConfig;
  const walk = (dir: string): string[] =>
    readdirSync(dir).flatMap((name) => {
      const full = path.join(dir, name);
      return statSync(full).isDirectory() ? walk(full) : [full];
    });
  return {
    name: 'loam-app-sw',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    writeBundle() {
      const out = path.resolve(config.root, config.build.outDir);
      const url = (file: string) => `/${path.relative(out, file).split(path.sep).join('/')}`;
      const files = [
        ...walk(path.join(out, 'assets')),
        ...walk(path.join(out, 'fonts')).filter((f) => f.endsWith('.woff2')),
        path.join(out, 'app/index.html'),
        path.join(out, 'favicon.svg'),
        path.join(out, 'logo.svg'),
      ].filter((f) => existsSync(f));
      const precache = [...new Set(files.map(url))].sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(readFileSync(f));
      const cacheName = `loam-app-${hash.digest('hex').slice(0, 12)}`;
      const source = `// Generated by vite.config.ts. Do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};
const KNOWN = new Set(PRECACHE);

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('loam-app-') && k !== CACHE).map((k) => caches.delete(k))),
    ),
  );
});

// Serve the app and its files from the cache. Everything else (the landing page, /install) is left to the
// browser untouched. /app and /app/ both open the app shell, so a link without the slash works offline too.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const isApp = request.mode === 'navigate' && (url.pathname === '/app' || url.pathname.startsWith('/app/'));
  const key = isApp ? '/app/index.html' : url.pathname;
  if (!isApp && !KNOWN.has(key)) return;
  event.respondWith(caches.match(key).then((hit) => hit || Response.error()));
});
`;
      writeFileSync(path.join(out, 'sw.js'), source);
    },
  };
}

/**
 * Static hosts (Cloudflare Pages) send /app to /app/ (keeping the query) and the download address to the file in GitHub
 * Releases (see `_redirects`, written below). The dev and preview servers do the same, so every link can be tried locally.
 */
function localRedirects(): Plugin {
  const redirect = (req: { url?: string }, res: { statusCode: number; setHeader(k: string, v: string): void; end(): void }, next: () => void) => {
    const url = req.url ?? '';
    if (url === '/app' || url.startsWith('/app?')) {
      res.statusCode = 308;
      res.setHeader('Location', `/app/${url.slice('/app'.length)}`);
      res.end();
      return;
    }
    if (url === site.download.path || url.startsWith(`${site.download.path}?`)) {
      res.statusCode = 302;
      res.setHeader('Location', site.releaseDownloadUrl);
      res.end();
      return;
    }
    next();
  };
  return {
    name: 'loam-local-redirects',
    configureServer: (server) => void server.middlewares.use(redirect),
    configurePreviewServer: (server) => void server.middlewares.use(redirect),
  };
}

/** `_headers` and `_redirects` for Cloudflare Pages, written from site.config.json so no address is typed twice. */
function hostingFiles(): Plugin {
  return {
    name: 'loam-hosting-files',
    apply: 'build',
    generateBundle() {
      const headers = readFileSync(path.resolve(here, '_headers.template'), 'utf8').replaceAll('{{analyticsOrigin}}', site.analytics.origin);
      this.emitFile({ type: 'asset', fileName: '_headers', source: headers });
      // The link people click lives on our own domain; GitHub serves the newest release's file straight as a download.
      this.emitFile({ type: 'asset', fileName: '_redirects', source: `${site.download.path} ${site.releaseDownloadUrl} 302\n` });
    },
  };
}

/**
 * Fills {{placeholders}} in the three HTML pages: addresses from site.config.json, and the numbers and story of the
 * sample knowledge base (summary.json, written by `npm run demo:build`), so the page cannot promise anything the
 * product does not show.
 */
function siteValues(): Plugin {
  const summary = JSON.parse(readFileSync(path.resolve(here, 'src/demo-data/summary.json'), 'utf8')) as SarahSummary;
  const n = (x: number) => x.toLocaleString('en-US');
  const demo = '/app?demo=1';
  const values: Record<string, string> = {
    typicalPercent: String(summary.numbers.typicalPercent),
    typicalBefore: n(summary.numbers.typicalBefore),
    typicalAfter: n(summary.numbers.typicalAfter),
    siteUrl: site.siteUrl,
    githubUrl: site.githubUrl,
    issuesUrl: site.issuesUrl,
    contactEmail: site.contactEmail,
    author: site.author,
    analyticsDomain: site.analytics.domain,
    analyticsScript: site.analytics.script,
    downloadPath: site.download.path,
    npmPackage: site.npmPackage,
    sarah: renderSarah(summary, { demo, processBase: `${demo}&process=`, skills: `${demo}&screen=skills`, health: `${demo}&screen=health` }),
    installAgents: renderInstallAgents(site.npmPackage, `${site.appUrl}`),
  };
  return {
    name: 'loam-site-values',
    transformIndexHtml: { order: 'pre', handler: (html) => html.replace(/\{\{(\w+)\}\}/g, (m, key: string) => values[key] ?? m) },
  };
}

export default defineConfig({
  root: here,
  // Three separate pages, no client-side routing: /app must serve app/index.html, never fall back to the landing page.
  appType: 'mpa',
  plugins: [react(), tailwindcss(), siteValues(), localRedirects(), hostingFiles(), appCsp(), appServiceWorker()],
  resolve: {
    alias: {
      '@': path.resolve(here, 'src'),
      // gray-matter and js-yaml mention Node built-ins they never call in the browser.
      fs: path.resolve(here, 'src/shims/empty.ts'),
      buffer: path.resolve(here, 'src/shims/empty.ts'),
    },
  },
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    target: 'es2022',
    // Vite's preload polyfill calls fetch() (for old browsers). The app promises to make no requests at all, and
    // preloading is only an optimisation, so the polyfill stays out.
    modulePreload: { polyfill: false },
    // The one big chunk is the token-counting vocabulary, fetched only when the Health screen opens.
    chunkSizeWarningLimit: 1100,
    // The landing page and the app are separate entries: visitors to / never download the app.
    rolldownOptions: {
      input: {
        landing: path.resolve(here, 'index.html'),
        install: path.resolve(here, 'install.html'),
        notFound: path.resolve(here, '404.html'),
        app: path.resolve(here, 'app/index.html'),
      },
      checks: { eval: false },
      onwarn(warning, defaultHandler) {
        // gray-matter's eval-based JS front-matter engine is dead code: Loam refuses every engine but YAML.
        if (warning.code === 'EVAL' && String(warning.id ?? '').includes('gray-matter')) return;
        defaultHandler(warning);
      },
    },
  },
  server: { port: 5173 },
  preview: { port: 4173 },
});
